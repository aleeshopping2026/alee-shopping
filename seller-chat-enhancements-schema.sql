-- ALEE SHOPPING chat enhancements: retention, mute duration, local history clearing and reports.
-- Run after seller-chat-schema.sql in the Supabase SQL Editor.

alter table public.seller_messages
  add column if not exists expires_at timestamptz;

alter table public.seller_chat_preferences
  add column if not exists mute_until timestamptz,
  add column if not exists disappearing_seconds integer not null default 0,
  add column if not exists cleared_at timestamptz;

create index if not exists seller_messages_expiry_idx
  on public.seller_messages (expires_at) where expires_at is not null;

-- Participants can remove expired messages while opening a conversation.
drop policy if exists "Participants can delete expired chat messages" on public.seller_messages;
create policy "Participants can delete expired chat messages" on public.seller_messages
  for delete to authenticated
  using (
    expires_at is not null and expires_at <= now()
    and exists (
      select 1 from public.seller_conversations c
      where c.id = conversation_id and (select auth.uid()) in (c.buyer_id, c.seller_id)
    )
  );
grant delete on public.seller_messages to authenticated;

-- Audio uploads are used by the in-chat voice recorder.
update storage.buckets
set allowed_mime_types = array[
  'image/jpeg','image/png','image/webp','image/gif','image/heic','image/heif','application/pdf',
  'text/plain','application/msword','application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'application/vnd.ms-excel','application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  'audio/webm','audio/mp4','audio/ogg','audio/mpeg'
]
where id = 'seller-chat-files';

create table if not exists public.seller_chat_reports (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.seller_conversations(id) on delete cascade,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reason text not null check (char_length(reason) between 1 and 120),
  created_at timestamptz not null default now()
);

alter table public.seller_chat_reports enable row level security;
drop policy if exists "Chat participants can report conversations" on public.seller_chat_reports;
create policy "Chat participants can report conversations" on public.seller_chat_reports
  for insert to authenticated
  with check (
    reporter_id = (select auth.uid())
    and exists (
      select 1 from public.seller_conversations c
      where c.id = conversation_id and (select auth.uid()) in (c.buyer_id, c.seller_id)
    )
  );
drop policy if exists "Reporters can view their chat reports" on public.seller_chat_reports;
create policy "Reporters can view their chat reports" on public.seller_chat_reports
  for select to authenticated using (reporter_id = (select auth.uid()));
grant select, insert on public.seller_chat_reports to authenticated;
grant usage, select on sequence public.seller_chat_reports_id_seq to authenticated;
