-- ALEE SHOPPING buyer/seller chat. Run once in Supabase SQL Editor.
create table if not exists public.seller_conversations (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid references public.seller_shops(id) on delete cascade,
  buyer_id uuid not null references auth.users(id) on delete cascade,
  seller_id uuid not null references auth.users(id) on delete cascade,
  buyer_label text not null default 'Buyer',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_message_at timestamptz not null default now(),
  constraint seller_conversations_no_self_chat check (buyer_id <> seller_id)
);

-- Existing seller chats remain intact. NULL shop_id identifies the built-in ALEE SHOPPING inbox.
alter table public.seller_conversations alter column shop_id drop not null;
alter table public.seller_conversations drop constraint if exists seller_conversations_shop_buyer_unique;
create unique index if not exists seller_conversations_shop_buyer_unique
  on public.seller_conversations(shop_id,buyer_id) where shop_id is not null;
create unique index if not exists seller_conversations_alee_buyer_unique
  on public.seller_conversations(buyer_id) where shop_id is null;

create table if not exists public.seller_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.seller_conversations(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  body text,
  attachment_path text,
  attachment_name text,
  attachment_mime text,
  created_at timestamptz not null default now()
);

-- Upgrade existing chat installations without deleting messages.
alter table public.seller_messages alter column body drop not null;
alter table public.seller_messages add column if not exists attachment_path text;
alter table public.seller_messages add column if not exists attachment_name text;
alter table public.seller_messages add column if not exists attachment_mime text;
alter table public.seller_messages drop constraint if exists seller_messages_body_check;
alter table public.seller_messages drop constraint if exists seller_messages_body_or_attachment_check;
alter table public.seller_messages add constraint seller_messages_body_or_attachment_check
  check ((body is not null and char_length(body) between 1 and 4000)
      or (attachment_path is not null and attachment_name is not null));

-- Per-user read and favourite settings work across phone and desktop.
create table if not exists public.seller_chat_preferences (
  user_id uuid not null references auth.users(id) on delete cascade,
  conversation_id uuid not null references public.seller_conversations(id) on delete cascade,
  is_favorite boolean not null default false,
  last_read_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, conversation_id)
);
alter table public.seller_chat_preferences add column if not exists is_archived boolean not null default false;
alter table public.seller_chat_preferences add column if not exists is_muted boolean not null default false;

-- A block by either participant prevents further messages.
create table if not exists public.seller_chat_blocks (
  user_id uuid not null references auth.users(id) on delete cascade,
  blocked_user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, blocked_user_id),
  constraint seller_chat_blocks_no_self check (user_id <> blocked_user_id)
);

create index if not exists seller_conversations_buyer_recent_idx
  on public.seller_conversations (buyer_id, last_message_at desc);
create index if not exists seller_conversations_seller_recent_idx
  on public.seller_conversations (seller_id, last_message_at desc);
create index if not exists seller_messages_conversation_recent_idx
  on public.seller_messages (conversation_id, created_at desc);

alter table public.seller_conversations enable row level security;
alter table public.seller_messages enable row level security;
alter table public.seller_chat_preferences enable row level security;
alter table public.seller_chat_blocks enable row level security;

drop policy if exists "Chat participants can read their conversations" on public.seller_conversations;
create policy "Chat participants can read their conversations" on public.seller_conversations
  for select to authenticated
  using ((select auth.uid()) in (buyer_id, seller_id));

drop policy if exists "Chat participants can read messages" on public.seller_messages;
create policy "Chat participants can read messages" on public.seller_messages
  for select to authenticated
  using (exists (
    select 1 from public.seller_conversations c
    where c.id = conversation_id and (select auth.uid()) in (c.buyer_id, c.seller_id)
  ));

drop policy if exists "Participants can send their own messages" on public.seller_messages;
create policy "Participants can send their own messages" on public.seller_messages
  for insert to authenticated
  with check (
    sender_id = (select auth.uid()) and exists (
      select 1 from public.seller_conversations c
      where c.id = conversation_id and (select auth.uid()) in (c.buyer_id, c.seller_id)
        and not exists (
          select 1 from public.seller_chat_blocks b
          where (b.user_id = (select auth.uid()) and b.blocked_user_id in (c.buyer_id,c.seller_id))
             or (b.blocked_user_id = (select auth.uid()) and b.user_id in (c.buyer_id,c.seller_id))
        )
    )
  );

grant select on public.seller_conversations, public.seller_messages to authenticated;
grant insert on public.seller_messages to authenticated;
grant usage, select on sequence public.seller_messages_id_seq to authenticated;

