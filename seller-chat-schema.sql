create or replace function public.get_or_create_seller_conversation(p_shop_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_buyer_id uuid := auth.uid();
  v_seller_id uuid;
  v_conversation_id uuid;
  v_buyer_label text := coalesce(nullif(auth.jwt() ->> 'email', ''), 'Buyer');
begin
  if v_buyer_id is null then
    raise exception 'Sign in is required to message a shop.' using errcode = '28000';
  end if;
  select owner_id into v_seller_id from public.seller_shops where id = p_shop_id;
  if v_seller_id is null then
    raise exception 'Shop not found.' using errcode = 'P0002';
  end if;
  if v_buyer_id = v_seller_id then
    raise exception 'You cannot start a chat with your own shop.' using errcode = '22023';
  end if;
  insert into public.seller_conversations (shop_id, buyer_id, seller_id, buyer_label)
  values (p_shop_id, v_buyer_id, v_seller_id, v_buyer_label)
  on conflict (shop_id, buyer_id) where shop_id is not null do update set updated_at = now()
  returning id into v_conversation_id;
  return v_conversation_id;
end;
$$;

revoke all on function public.get_or_create_seller_conversation(uuid) from public;
grant execute on function public.get_or_create_seller_conversation(uuid) to authenticated;

create or replace function public.touch_seller_conversation_after_message()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.seller_conversations
  set last_message_at = new.created_at, updated_at = new.created_at
  where id = new.conversation_id;
  return new;
end;
$$;

drop trigger if exists seller_message_touch_conversation on public.seller_messages;
create trigger seller_message_touch_conversation
  after insert on public.seller_messages
  for each row execute function public.touch_seller_conversation_after_message();

