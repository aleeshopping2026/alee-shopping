-- WebRTC voice/video call signaling. Audio/video itself streams directly between
-- the two browsers; this table only carries the offer, answer and ICE candidates.
create table if not exists public.seller_call_signals (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.seller_conversations(id) on delete cascade,
  call_id uuid not null,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('offer','answer','ice','end','reject')),
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint seller_call_signals_no_self_call check (sender_id <> recipient_id)
);

create index if not exists seller_call_signals_conversation_recent_idx
  on public.seller_call_signals (conversation_id, id desc);
alter table public.seller_call_signals enable row level security;

drop policy if exists "Chat participants can receive call signals" on public.seller_call_signals;
create policy "Chat participants can receive call signals" on public.seller_call_signals
  for select to authenticated using (
    (select auth.uid()) in (sender_id, recipient_id) and exists (
      select 1 from public.seller_conversations c
      where c.id = conversation_id and (select auth.uid()) in (c.buyer_id, c.seller_id)
    )
  );

drop policy if exists "Chat participants can send call signals to each other" on public.seller_call_signals;
create policy "Chat participants can send call signals to each other" on public.seller_call_signals
  for insert to authenticated with check (
    sender_id = (select auth.uid()) and exists (
      select 1 from public.seller_conversations c
      where c.id = conversation_id
        and (select auth.uid()) in (c.buyer_id, c.seller_id)
        and recipient_id = case
          when (select auth.uid()) = c.buyer_id then c.seller_id
          else c.buyer_id
        end
    )
  );

grant select, insert on public.seller_call_signals to authenticated;
grant usage, select on sequence public.seller_call_signals_id_seq to authenticated;

do $$ begin
  alter publication supabase_realtime add table public.seller_call_signals;
exception when duplicate_object then null;
end $$;
