alter table public.seller_shops add column if not exists shop_category text not null default 'Other';
alter table public.seller_shops add column if not exists youtube_url text;
alter table public.seller_shops add column if not exists instagram_url text;
alter table public.seller_shops add column if not exists facebook_url text;
alter table public.seller_shops add column if not exists bio text not null default '' check (char_length(bio) <= 600);
alter table public.seller_shops add column if not exists tiktok_url text;

create table if not exists public.seller_products (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  shop_id uuid not null references public.seller_shops(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 120),
  price numeric(12,2) not null check (price > 0),
  category text not null,
  category_label text not null,
  description text not null check (char_length(description) between 1 and 2000),
  features text[] not null default '{}',
  sizes text[] not null default '{}',
  image_urls text[] not null check (cardinality(image_urls) between 1 and 10),
  created_at timestamptz not null default now(),
  constraint seller_products_owner_shop_fk foreign key (shop_id, owner_id)
    references public.seller_shops(id, owner_id) on delete cascade
);

create index if not exists seller_products_shop_created_idx
  on public.seller_products(shop_id, created_at desc);
create index if not exists seller_products_owner_created_idx
  on public.seller_products(owner_id, created_at desc);

alter table public.seller_shops enable row level security;
alter table public.seller_products enable row level security;

