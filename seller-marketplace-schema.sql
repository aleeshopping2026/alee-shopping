create table if not exists public.seller_shops (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null unique references auth.users(id) on delete cascade,
  shop_name text not null check (char_length(shop_name) between 2 and 80),
  phone text not null check (char_length(phone) between 5 and 40),
  phone2 text,
  address text not null check (char_length(address) between 3 and 400),
  external_link text,
  logo_url text,
  shop_category text not null default 'Other',
  youtube_url text,
  instagram_url text,
  facebook_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint seller_shops_id_owner_unique unique (id, owner_id)
);

